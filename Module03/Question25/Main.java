public class Main {
    public static void main(String[] args) {
        int negativeNum = -25;
        double value = 64.0;
        int a = 45;
        int b = 80;

        System.out.println("Math.abs(" + negativeNum + "): " + Math.abs(negativeNum));
        System.out.println("Math.sqrt(" + value + "): " + Math.sqrt(value));
        System.out.println("Math.max(" + a + ", " + b + "): " + Math.max(a, b));
        System.out.println("Math.random(): " + Math.random());
    }
}
